def rx(words):
    """Регулярка по границам слова из списка основ."""
    return re.compile(r'(?:(?<=\s)|^)(?:' + '|'.join(words) + r')(?:(?=\s)|$)', re.I)


def rxs(subs):
    """Регулярка по подстроке — только там, где это осознанно."""
    return re.compile('|'.join(subs), re.I)


