ODNOSLOVNIKI = {'ремонт', 'дизайн', 'квартира', 'квартиры', 'отделка',
                'приемка', 'приёмка', 'комплектация', 'интерьер', 'штукатурка',
                'перепланировка', 'новостройка', 'вторичка'}

FILTERS = [
    ('чужие смыслы', CHUZHIE_SMYSLY),
    ('бренды', BRENDY),
    ('чужой профиль', CHUZHOY_PROFIL),
    ('недвижимость и объявления', NEDVIZH),
    ('сделать самому', DIY),
    ('работа и обучение', RABOTA),
    ('чужая география', CHUZHAYA_GEO),
]


def main():
    raw = json.load(open(RAW, encoding='utf-8'))
    print('на входе фраз: %d' % len(raw))

    kom, info, otsev = {}, {}, {}
    reasons = collections.Counter()

    for w, p in raw.items():
        if w in ODNOSLOVNIKI:
            otsev[w] = dict(p, reason='однословник')
            reasons['однословник'] += 1
            continue
        hit = None
        for name, pat in FILTERS:
            if pat.search(w):
                hit = name
                break
        if hit:
            otsev[w] = dict(p, reason=hit)
            reasons[hit] += 1
            continue
        if p.get('isquest') or INFO.search(w):
            info[w] = p
        else:
            kom[w] = p

    json.dump(kom, open(os.path.join(OUT, 'ядро_коммерч.json'), 'w', encoding='utf-8'),
              ensure_ascii=False)
    json.dump(info, open(os.path.join(OUT, 'ядро_инфо.json'), 'w', encoding='utf-8'),
              ensure_ascii=False)
    json.dump(otsev, open(os.path.join(OUT, 'ядро_отсеяно.json'), 'w', encoding='utf-8'),
              ensure_ascii=False)

    print('\nкоммерческих кандидатов: %d' % len(kom))
    print('информационных (в блог):  %d' % len(info))
    print('отсеяно:                  %d' % len(otsev))
    print('сходимость: %d + %d + %d = %d, на входе %d — %s'
          % (len(kom), len(info), len(otsev), len(kom) + len(info) + len(otsev),
             len(raw), 'ок' if len(kom) + len(info) + len(otsev) == len(raw) else 'РАСХОЖДЕНИЕ'))

    print('\n=== причины отсева ===')
    for r, n in reasons.most_common():
        print('  %-28s %d' % (r, n))

    print('\n=== проверка на ложные срабатывания: верх каждой категории по частоте ===')
    by_reason = collections.defaultdict(list)
    for w, p in otsev.items():
        by_reason[p['reason']].append((p.get('wsk', 0), w))
    for r in reasons:
        top = sorted(by_reason[r], reverse=True)[:6]
        print('\n  [%s]' % r)
        for f, w in top:
            print('     %-58s %s' % (w[:58], f))


main()
