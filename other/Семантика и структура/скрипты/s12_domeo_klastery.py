RX = [(n, re.compile(p, re.I)) for n, p in NAPRAVLENIYA]


def main():
    raw = json.load(open(os.path.join(MAT, 'ядро_сырое.json'), encoding='utf-8'))
    print('сырых фраз: %d' % len(raw))

    # уже разложенное ядро — чтобы не тянуть повторно
    done = set()
    p = os.path.join(MAT, 'ядро_разложено.json')
    if os.path.exists(p):
        done = set(json.load(open(p, encoding='utf-8')))
    print('уже в ядре: %d' % len(done))

    found = collections.defaultdict(list)
    for w, v in raw.items():
        for name, pat in RX:
            if pat.search(w):
                found[name].append((v.get('wsk', 0), w, w in done))
                break

    out = {}
    print('\n%-34s %-7s %-7s %-9s %s' % ('направление', 'фраз', 'новых', 'спрос РФ', 'пример'))
    print('-' * 110)
    for name, _ in NAPRAVLENIYA:
        items = sorted(found.get(name, []), reverse=True)
        if not items:
            print('%-34s %-7s %-7s %-9s %s' % (name, 0, 0, 0, '— ничего не нашлось'))
            continue
        new = [x for x in items if not x[2]]
        top = items[0]
        print('%-34s %-7d %-7d %-9d %s' % (name, len(items), len(new),
                                           sum(x[0] for x in items), top[1][:44]))
        out[name] = [w for _, w, _ in items]

    json.dump(out, open(os.path.join(MAT, 'кандидаты_domeo.json'), 'w', encoding='utf-8'),
              ensure_ascii=False)
    allw = sorted({w for lst in out.values() for w in lst})
    print('\nвсего кандидатов: %d, из них новых (нет в ядре): %d'
          % (len(allw), len([w for w in allw if w not in done])))
    print('сохранено: материалы/кандидаты_domeo.json')


main()
