RULES = [(u, n, s, re.compile(rx, re.I), st) for u, n, s, rx, st in PAGES]


def assign(phrase):
    for url, name, sect, pat, status in RULES:
        if pat.search(phrase):
            return url, name, sect
    return '/remont-kvartir/', 'Ремонт квартир под ключ', 'Ремонт квартир'


def main():
    core = json.load(open(os.path.join(MAT, 'ядро_финал.json'), encoding='utf-8'))
    print('фраз в ядре: %d' % len(core))

    pages = collections.defaultdict(list)
    for w, v in core.items():
        url, name, sect = assign(w)
        v['url'] = url
        v['stranica'] = name
        v['razdel'] = sect
        pages[url].append((v['quoted'], w))

    json.dump(core, open(os.path.join(MAT, 'ядро_разложено.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

    meta = {u: (n, s, st) for u, n, s, _, st in PAGES}
    rows = []
    for url, items in pages.items():
        n, s, st = meta[url]
        rows.append((sum(q for q, _ in items), len(items), url, n, s, st,
                     sorted(items, reverse=True)[0][1]))
    rows.sort(reverse=True)

    print('\n%-34s %-6s %-8s %-30s %s' % ('URL', 'фраз', 'спрос', 'страница', 'маркер'))
    print('-' * 118)
    for demand, cnt, url, n, s, st, marker in rows:
        print('%-34s %-6d %-8d %-30s %s' % (url[:34], cnt, demand, n[:30], marker[:34]))

    print('\nстраниц с фразами: %d из %d в таблице решений' % (len(rows), len(PAGES)))
    empty = [u for u, n, s, _, st in PAGES if u not in pages]
    if empty:
        print('\nбез единой фразы (кандидаты в «Не создавать»):')
        for u in empty:
            print('   %s' % u)


main()
