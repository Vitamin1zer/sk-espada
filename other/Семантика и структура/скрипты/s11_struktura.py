ORDER = list(META.keys())


KOM_PORE = 50   # порог коммерческой фразы для услуг, принят на шаге 0


def main():
    core = json.load(open(os.path.join(MAT, 'ядро_разложено.json'), encoding='utf-8'))
    cpath = os.path.join(MAT, 'коммерциализация.json')
    comm = json.load(open(cpath, encoding='utf-8')) if os.path.exists(cpath) else {}

    stat = collections.defaultdict(
        lambda: {'n': 0, 'q': 0, 'qk': 0, 'nk': 0, 'marker': '', 'top': 0})
    for w, v in core.items():
        s = stat[v['url']]
        s['n'] += 1
        s['q'] += v['quoted']
        c = comm.get(w)
        is_kom = isinstance(c, (int, float)) and c >= KOM_PORE
        if is_kom:
            s['nk'] += 1
            s['qk'] += v['quoted']
        # маркером берём самую частотную КОММЕРЧЕСКУЮ фразу: информационная
        # фраза маркером быть не может
        if is_kom and v['quoted'] > s['top']:
            s['top'] = v['quoted']
            s['marker'] = w
    # если коммерческих фраз у страницы нет — маркер по самой частотной вообще
    for url, s in stat.items():
        if not s['marker']:
            best = max(((v['quoted'], w) for w, v in core.items() if v['url'] == url),
                       default=(0, ''))
            s['marker'] = best[1]

    def status(url):
        m = META[url]
        old = m[2]
        s = stat.get(url, {'n': 0, 'q': 0})
        if url in ('/', '/design/', '/priemka/'):
            return 'Есть на сайте'
        if old:
            return 'Редирект'
        if META[url][5] == '':          # мета не написаны — решение «не создавать»
            return 'Не создавать'
        return 'Необходимо создать'

    def verdict(url):
        s = stat.get(url)
        if not s:
            return 'Спроса не найдено'
        if s['q'] < 10:
            return 'Спроса нет'
        if s['nk'] == 0:
            return 'Интент информационный'
        if s['n'] >= 30:
            return 'Ядро полное'
        if s['n'] >= 10:
            return 'Рабочее ядро'
        return 'Тонко'

    pages_rows, meta_rows, demand_rows = [], [], []
    for url in ORDER:
        name, sect, old, title, descr, h1 = META[url]
        st = status(url)
        pages_rows.append([st, url, old, name, '', '', ''])
        if title:
            meta_rows.append([name, title, len(title), descr, len(descr), h1, len(h1)])
        s = stat.get(url, {'n': 0, 'q': 0, 'qk': 0, 'nk': 0, 'marker': ''})
        demand_rows.append([url, name, sect, st, s['n'], s['q'], s['nk'], s['qk'],
                            s['marker'], verdict(url)])

    out = os.path.join(PROJ, 'СТРУКТУРА САЙТА _ СК ЭСПАДА _ SEO VICTORY.xlsx')
    if os.path.exists(out):
        bak = out.replace('.xlsx', ' (шаблон).xlsx')
        if not os.path.exists(bak):
            shutil.copyfile(out, bak)

    n1, n2 = build_structure(out, pages_rows, MENU, meta_rows)

    # четвёртый лист: на каком основании принято решение по каждой странице
    from openpyxl import load_workbook
    from s10_sobrat_xlsx import sheet, put
    wb = load_workbook(out)
    from openpyxl.utils import get_column_letter
    ws = wb.create_sheet('Спрос по страницам')
    hdr = ['URL', 'Название', 'Раздел', 'Статус', 'Фраз', 'Спрос "Ч"',
           'Коммерч. фраз', 'Коммерч. спрос', 'Маркер', 'Вердикт']
    from openpyxl.styles import Font, PatternFill, Alignment
    for i, h in enumerate(hdr, 1):
        c = ws.cell(1, i, h)
        c.fill = PatternFill('solid', fgColor='FF000000')
        c.font = Font(name='Inter', size=10, bold=True, color='FFFFFFFF')
    for i, w in enumerate([34, 34, 16, 20, 8, 11, 14, 15, 40, 22], 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for r, row in enumerate(sorted(demand_rows, key=lambda x: -x[7]), 2):
        for i, v in enumerate(row, 1):
            ws.cell(r, i, v).font = Font(name='Inter', size=10)
    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = 'A1:J%d' % (len(demand_rows) + 1)
    wb.save(out)

    print('СТРУКТУРА САЙТА собрана: %d страниц, %d наборов мета-тегов' % (n1, n2))
    print('пунктов меню первого уровня: %d' % len(MENU))
    bad = [r for r in meta_rows if r[2] > 75 or (r[4] and r[4] > 200)]
    if bad:
        print('\nвыходят за рекомендуемую длину:')
        for r in bad:
            print('   %-36s Title %d, Description %d' % (r[0][:36], r[2], r[4]))


main()
